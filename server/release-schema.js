// Additive migration: never rebuild appointments or change its legacy status CHECK.
// no_show_at is a separate irreversible outcome; API status is projected as no_show.
const waived =
  'COALESCE((SELECT SUM(c.amount_paise) FROM charge_adjustments c WHERE c.appointment_id=a.id),0)';
const effective = `(CASE WHEN a.status='cancelled' THEN 0 ELSE MAX(a.fee_paise-${waived},0) END)`;
const net =
  "COALESCE((SELECT SUM(CASE WHEN p.kind='payment' THEN p.amount_paise ELSE -p.amount_paise END) FROM payment_entries p WHERE p.appointment_id=a.id),0)";
async function migrate({ run, all }) {
  // Normalize metadata generated by legacy DEFAULT CURRENT_TIMESTAMP on NEW rows only.
  // Slot start/end values remain clinic wall time; no historical records are converted.
  for (const [table, column] of [
    ['users', 'created_at'],
    ['appointments', 'created_at'],
    ['notifications', 'created_at'],
    ['email_jobs', 'next_attempt_at'],
  ]) {
    await run(
      `CREATE TRIGGER IF NOT EXISTS utc_new_${table}_${column} AFTER INSERT ON ${table} WHEN NEW.${column} IS NOT NULL AND NEW.${column} NOT GLOB '????-??-??T??:??:??.???Z' BEGIN UPDATE ${table} SET ${column}=strftime('%Y-%m-%dT%H:%M:%fZ',NEW.${column}) WHERE id=NEW.id; END`,
    );
  }
  const columns = await all('PRAGMA table_info(appointments)');
  for (const [name, type] of Object.entries({
    no_show_at: 'TEXT',
    no_show_reason: 'TEXT',
    no_show_by: 'INTEGER REFERENCES users(id)',
    no_show_key: 'TEXT',
    change_reason: 'TEXT',
    change_by: 'INTEGER REFERENCES users(id)',
    change_at: 'TEXT',
  }))
    if (!columns.some((c) => c.name === name))
      await run(`ALTER TABLE appointments ADD COLUMN ${name} ${type}`);
  if (!(await all('PRAGMA table_info(payment_entries)')).some((c) => c.name === 'refund_type'))
    await run(
      "ALTER TABLE payment_entries ADD COLUMN refund_type TEXT NOT NULL DEFAULT 'correction' CHECK(refund_type IN ('correction','goodwill'))",
    );
  await run(`CREATE TABLE IF NOT EXISTS charge_adjustments (
    id INTEGER PRIMARY KEY,appointment_id INTEGER NOT NULL REFERENCES appointments(id),
    amount_paise INTEGER NOT NULL CHECK(typeof(amount_paise)='integer' AND amount_paise BETWEEN 1 AND 10000000),
    reason TEXT NOT NULL CHECK(length(trim(reason)) BETWEEN 5 AND 500),
    recorded_by INTEGER NOT NULL REFERENCES users(id),recorded_at TEXT NOT NULL CHECK(length(recorded_at)=24 AND recorded_at GLOB '????-??-??T??:??:??.???Z' AND julianday(recorded_at) IS NOT NULL),
    kind TEXT NOT NULL CHECK(kind IN ('waiver','goodwill','no_show')),
    payment_entry_id INTEGER UNIQUE REFERENCES payment_entries(id),
    idempotency_key TEXT UNIQUE NOT NULL CHECK(length(idempotency_key)=36 AND substr(idempotency_key,9,1)='-' AND substr(idempotency_key,14,1)='-' AND substr(idempotency_key,19,1)='-' AND substr(idempotency_key,24,1)='-' AND length(replace(idempotency_key,'-',''))=32 AND lower(replace(idempotency_key,'-','')) NOT GLOB '*[^0-9a-f]*' AND substr(idempotency_key,15,1) GLOB '[1-8]' AND lower(substr(idempotency_key,20,1)) GLOB '[89ab]'), CHECK((kind='goodwill' AND payment_entry_id IS NOT NULL) OR (kind!='goodwill' AND payment_entry_id IS NULL)))`);
  await run(
    'CREATE INDEX IF NOT EXISTS adjustment_appointment ON charge_adjustments(appointment_id,id)',
  );
  await run(`CREATE TABLE IF NOT EXISTS appointment_history (
    id INTEGER PRIMARY KEY,appointment_id INTEGER NOT NULL REFERENCES appointments(id),
    kind TEXT NOT NULL CHECK(kind IN ('reschedule','no_show')),
    old_slot_id INTEGER NOT NULL REFERENCES slots(id),new_slot_id INTEGER NOT NULL REFERENCES slots(id),
    old_start_time TEXT NOT NULL,new_start_time TEXT NOT NULL,reason TEXT NOT NULL,
    recorded_at TEXT NOT NULL,recorded_by INTEGER NOT NULL REFERENCES users(id))`);
  await run(
    'CREATE INDEX IF NOT EXISTS history_appointment ON appointment_history(appointment_id,id)',
  );
  for (const table of ['charge_adjustments', 'appointment_history'])
    for (const op of ['UPDATE', 'DELETE'])
      await run(
        `CREATE TRIGGER IF NOT EXISTS ${table}_no_${op.toLowerCase()} BEFORE ${op} ON ${table} BEGIN SELECT RAISE(ABORT,'Records are append-only'); END`,
      );
  await run(`CREATE TRIGGER IF NOT EXISTS adjustment_capacity BEFORE INSERT ON charge_adjustments BEGIN
    SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM appointments a WHERE a.id=NEW.appointment_id AND NEW.amount_paise<=a.fee_paise-${waived}) THEN RAISE(ABORT,'Adjustment exceeds remaining charge') END;
    SELECT CASE WHEN NEW.kind='goodwill' AND NOT EXISTS(SELECT 1 FROM payment_entries WHERE id=NEW.payment_entry_id AND appointment_id=NEW.appointment_id AND kind='refund' AND refund_type='goodwill' AND amount_paise=NEW.amount_paise AND notes=NEW.reason AND recorded_by=NEW.recorded_by AND recorded_at=NEW.recorded_at AND idempotency_key=NEW.idempotency_key) THEN RAISE(ABORT,'Goodwill adjustment must match refund') END;
    SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM users WHERE id=NEW.recorded_by AND role='admin') THEN RAISE(ABORT,'Administrator required') END;
  END`);
  // Separate additive trigger also protects databases initialized by the earlier release draft.
  // Goodwill must reduce an effective charge; cancellation has no charge left to reduce.
  await run(`CREATE TRIGGER IF NOT EXISTS goodwill_effective_capacity BEFORE INSERT ON charge_adjustments WHEN NEW.kind='goodwill' BEGIN
    SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM appointments a WHERE a.id=NEW.appointment_id AND NEW.amount_paise<=${effective}) THEN RAISE(ABORT,'Goodwill exceeds effective charge') END;
  END`);
  await run(
    `CREATE TRIGGER IF NOT EXISTS adjusted_fee_snapshot BEFORE UPDATE OF fee_paise ON appointments WHEN EXISTS(SELECT 1 FROM charge_adjustments WHERE appointment_id=OLD.id) BEGIN SELECT RAISE(ABORT,'Adjusted charge snapshot is immutable'); END`,
  );
  await run(`CREATE TRIGGER IF NOT EXISTS goodwill_adjustment AFTER INSERT ON payment_entries WHEN NEW.kind='refund' AND NEW.refund_type='goodwill' BEGIN
    INSERT INTO charge_adjustments(appointment_id,amount_paise,reason,recorded_by,recorded_at,kind,payment_entry_id,idempotency_key) VALUES(NEW.appointment_id,NEW.amount_paise,NEW.notes,NEW.recorded_by,NEW.recorded_at,'goodwill',NEW.id,NEW.idempotency_key);
  END`);
  await run(
    `CREATE TRIGGER IF NOT EXISTS no_show_terminal BEFORE UPDATE ON appointments WHEN OLD.no_show_at IS NOT NULL AND (NEW.status IS NOT OLD.status OR NEW.slot_id IS NOT OLD.slot_id OR NEW.checked_in_at IS NOT OLD.checked_in_at OR NEW.no_show_at IS NOT OLD.no_show_at OR NEW.no_show_reason IS NOT OLD.no_show_reason OR NEW.no_show_by IS NOT OLD.no_show_by OR NEW.no_show_key IS NOT OLD.no_show_key) BEGIN SELECT RAISE(ABORT,'No-show is terminal'); END`,
  );
  await run(`CREATE TRIGGER IF NOT EXISTS no_show_eligible BEFORE UPDATE OF no_show_at ON appointments WHEN OLD.no_show_at IS NULL AND NEW.no_show_at IS NOT NULL BEGIN
    SELECT CASE WHEN OLD.status!='booked' OR OLD.checked_in_at IS NOT NULL OR NEW.no_show_by IS NULL OR NOT EXISTS(SELECT 1 FROM users WHERE id=NEW.no_show_by AND role='admin') OR length(trim(COALESCE(NEW.no_show_reason,''))) NOT BETWEEN 5 AND 500 OR NOT EXISTS(SELECT 1 FROM slots WHERE id=OLD.slot_id AND end_time<strftime('%Y-%m-%dT%H:%M:%S','now','+330 minutes')) THEN RAISE(ABORT,'Ineligible no-show') END;
  END`);
  await run(`CREATE TRIGGER IF NOT EXISTS no_show_record AFTER UPDATE OF no_show_at ON appointments WHEN OLD.no_show_at IS NULL AND NEW.no_show_at IS NOT NULL BEGIN
    INSERT INTO charge_adjustments(appointment_id,amount_paise,reason,recorded_by,recorded_at,kind,idempotency_key)
      SELECT a.id,a.fee_paise-${waived},NEW.no_show_reason,NEW.no_show_by,NEW.no_show_at,'no_show',NEW.no_show_key FROM appointments a WHERE a.id=NEW.id AND a.fee_paise-${waived}>0;
    INSERT INTO appointment_history(appointment_id,kind,old_slot_id,new_slot_id,old_start_time,new_start_time,reason,recorded_at,recorded_by)
      SELECT NEW.id,'no_show',OLD.slot_id,NEW.slot_id,start_time,start_time,NEW.no_show_reason,NEW.no_show_at,NEW.no_show_by FROM slots WHERE id=NEW.slot_id;
  END`);
  await run(`CREATE TRIGGER IF NOT EXISTS reschedule_record AFTER UPDATE OF slot_id ON appointments WHEN NEW.slot_id!=OLD.slot_id BEGIN
    INSERT INTO appointment_history(appointment_id,kind,old_slot_id,new_slot_id,old_start_time,new_start_time,reason,recorded_at,recorded_by)
      SELECT NEW.id,'reschedule',OLD.slot_id,NEW.slot_id,o.start_time,n.start_time,NEW.change_reason,NEW.change_at,NEW.change_by FROM slots o,slots n WHERE o.id=OLD.slot_id AND n.id=NEW.slot_id;
    INSERT INTO notifications(user_id,appointment_id,title,message,reason,created_at)
      SELECT NEW.patient_id,NEW.id,'Appointment rescheduled','Your appointment moved from '||o.start_time||' to '||n.start_time||'. Reason: '||NEW.change_reason,NEW.change_reason,NEW.change_at FROM slots o,slots n WHERE o.id=OLD.slot_id AND n.id=NEW.slot_id;
    INSERT INTO email_jobs(notification_id,recipient,next_attempt_at) SELECT last_insert_rowid(),email,NEW.change_at FROM users WHERE id=NEW.patient_id;
  END`);
}
module.exports = { migrate, waived, effective, net };
